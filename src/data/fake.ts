type Line = [ingredientId: string, gramsPerServing: number | null, amountText: string];

let nextId = 1;
const recipe = (
  name: string,
  type: string,
  cookingTime: string,
  servingsOriginal: number,
  lines: Line[],
  summary: string,
  steps: string[],
): { recipe: Recipe; detail: RecipeDetail } => {
  const id = nextId++;
  const pantryIds = new Set(fakeIngredients.filter((i) => i.pantry).map((i) => i.id));
  return {
    recipe: {
      id,
      name,
      type,
      cookingTime,
      level: "초보환영",
      servingsOriginal,
      ingredients: lines.map(([ingredientId, grams, amountText]) => ({
        ingredientId,
        grams,
        amountText,
        role: pantryIds.has(ingredientId) ? "양념" : "주재료",
        vague: !pantryIds.has(ingredientId) && amountText === "약간",
      })),
    },
    detail: { id, summary, steps: steps.map((text, i) => ({ no: i + 1, text, tip: null })) },
  };
};

